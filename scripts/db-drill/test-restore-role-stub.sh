#!/usr/bin/env bash
# Local-only synthetic regression for the ACL role stub used by the cloud
# restore drill. This never reads an external DSN, publishes ports, or writes
# an artifact. All database-tool output is suppressed; only fixed stage names
# are printed on failure.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "${repo_root}"

if ! command -v docker >/dev/null 2>&1; then
  echo "FAIL: docker-unavailable" >&2
  exit 1
fi

suffix="${BASHPID}"
source_container="sunrise-role-stub-source-${suffix}"
restore_container="sunrise-role-stub-restore-${suffix}"
cleanup() {
  docker stop "${source_container}" "${restore_container}" >/dev/null 2>&1 || true
}
trap cleanup EXIT

quiet() {
  local stage="$1"
  shift
  if ! "$@" >/dev/null 2>&1; then
    echo "FAIL: ${stage}" >&2
    exit 1
  fi
}

expect_value() {
  local stage="$1" expected="$2" actual
  shift 2
  if ! actual="$("$@" 2>/dev/null)" || [[ "${actual}" != "${expected}" ]]; then
    echo "FAIL: ${stage}" >&2
    exit 1
  fi
}

start_pg() {
  local container="$1"
  quiet "${container}-start" docker run --rm --detach --network none \
    --name "${container}" -e POSTGRES_HOST_AUTH_METHOD=trust postgres:17
  for _ in $(seq 1 45); do
    if docker exec "${container}" pg_isready -U postgres >/dev/null 2>&1; then
      return 0
    fi
    sleep 1
  done
  echo "FAIL: ${container}-ready" >&2
  exit 1
}

start_pg "${source_container}"
quiet source-roles docker exec -i "${source_container}" \
  psql -X -v ON_ERROR_STOP=1 -U postgres -d postgres <<'SQL'
CREATE ROLE app_user NOLOGIN;
CREATE ROLE backup_ro NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION BYPASSRLS;
CREATE ROLE synthetic_backup_login LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
GRANT backup_ro TO synthetic_backup_login;
CREATE DATABASE role_stub_source;
GRANT CONNECT ON DATABASE role_stub_source TO synthetic_backup_login;
SQL

quiet source-fixture docker exec -i "${source_container}" \
  psql -X -v ON_ERROR_STOP=1 -U postgres -d role_stub_source <<'SQL'
CREATE TABLE public.reservations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant text NOT NULL
);
ALTER TABLE public.reservations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reservations FORCE ROW LEVEL SECURITY;
CREATE POLICY app_user_tenant ON public.reservations
  FOR SELECT TO app_user USING (tenant = 'alpha');
GRANT SELECT ON public.reservations TO app_user;
GRANT USAGE ON SCHEMA public TO backup_ro;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO backup_ro;
GRANT SELECT ON ALL SEQUENCES IN SCHEMA public TO backup_ro;
INSERT INTO public.reservations (tenant) VALUES ('alpha'), ('beta');
SQL

quiet source-dump docker exec "${source_container}" pg_dump \
  --host=127.0.0.1 --username=synthetic_backup_login --role=backup_ro \
  --format=custom --schema=public --no-owner \
  --file=/tmp/role-stub.dump role_stub_source

start_pg "${restore_container}"
quiet restore-roles docker exec -i "${restore_container}" \
  psql -X -v ON_ERROR_STOP=1 -U postgres -d postgres <<'SQL'
CREATE ROLE app_user NOLOGIN;
CREATE DATABASE drill;
SQL
if ! docker cp "${source_container}:/tmp/role-stub.dump" - 2>/dev/null \
  | docker cp - "${restore_container}:/tmp/" >/dev/null 2>&1; then
  echo "FAIL: dump-transfer" >&2
  exit 1
fi
if ! docker exec "${restore_container}" pg_restore --list /tmp/role-stub.dump 2>/dev/null \
  | grep -vE '^[0-9]+; [0-9]+ [0-9]+ SCHEMA - public ' \
  | docker exec -i "${restore_container}" sh -c 'cat > /tmp/toc.filtered' >/dev/null 2>&1; then
  echo "FAIL: toc-filter" >&2
  exit 1
fi

restore_args=(pg_restore --no-owner --exit-on-error --single-transaction \
  --use-list=/tmp/toc.filtered --dbname=drill /tmp/role-stub.dump)
if docker exec -u postgres "${restore_container}" "${restore_args[@]}" >/dev/null 2>&1; then
  echo "FAIL: restore-without-stub-unexpectedly-passed" >&2
  exit 1
fi
expect_value failed-restore-rollback t docker exec -u postgres "${restore_container}" \
  psql -X -At -v ON_ERROR_STOP=1 -d drill \
  -c "SELECT to_regclass('public.reservations') IS NULL"

run_workflow_restore_prepare() {
  node - 2>/dev/null <<'NODE' \
    | docker exec -i "${restore_container}" psql -X -q -v ON_ERROR_STOP=1 -U postgres -d drill >/dev/null 2>&1
const fs = require("node:fs");
const yaml = require("js-yaml");
const workflow = yaml.load(fs.readFileSync(".github/workflows/db-backup-restore-drill.yml", "utf8"));
const job = Object.values(workflow.jobs)[0];
const restore = job.steps.find((step) => step.name === "Restore drill into isolated service DB");
const match = restore?.run?.match(/drill_quiet restore-prepare - psql[^\n]*<<'SQL'\n([\s\S]*?)\nSQL(?:\n|$)/);
if (!match || /^\s*#/m.test(match[1])) process.exit(1);
process.stdout.write(`${match[1]}\n`);
NODE
}
if ! run_workflow_restore_prepare; then
  echo "FAIL: restore-prepare-SQL" >&2
  exit 1
fi
quiet restore-with-stub docker exec -u postgres "${restore_container}" "${restore_args[@]}"
expect_value verify-restored-state t docker exec -u postgres "${restore_container}" \
  psql -X -At -v ON_ERROR_STOP=1 -d drill -c "
    SELECT (SELECT count(*) FROM public.reservations) = 2
      AND (SELECT relrowsecurity AND relforcerowsecurity
             FROM pg_class WHERE oid = 'public.reservations'::regclass)
      AND (SELECT count(*) = 1 FROM pg_policies
             WHERE schemaname = 'public' AND tablename = 'reservations')
      AND has_table_privilege('backup_ro', 'public.reservations', 'SELECT')
      AND NOT has_table_privilege('backup_ro', 'public.reservations', 'INSERT')
      AND NOT (SELECT rolcanlogin OR rolsuper OR rolcreatedb OR rolcreaterole
                      OR rolreplication OR rolbypassrls
                 FROM pg_roles WHERE rolname = 'backup_ro')
      AND (SELECT last_value = 2 FROM public.reservations_id_seq)
  "

quiet synthetic-default-acl-fixture docker exec -i "${source_container}" \
  psql -X -v ON_ERROR_STOP=1 -U postgres -d role_stub_source <<'SQL'
CREATE ROLE synthetic_owner NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
GRANT USAGE, CREATE ON SCHEMA public TO synthetic_owner;
ALTER DEFAULT PRIVILEGES FOR ROLE synthetic_owner IN SCHEMA public
  GRANT SELECT ON TABLES TO backup_ro;
ALTER DEFAULT PRIVILEGES FOR ROLE synthetic_owner IN SCHEMA public
  GRANT SELECT ON SEQUENCES TO backup_ro;
SET ROLE synthetic_owner;
CREATE TABLE public.synthetic_owned (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  marker text NOT NULL
);
INSERT INTO public.synthetic_owned(marker) VALUES ('synthetic only');
RESET ROLE;
SQL
quiet owner-dump docker exec "${source_container}" pg_dump \
  --host=127.0.0.1 --username=synthetic_backup_login --role=backup_ro \
  --format=custom --schema=public --no-owner \
  --file=/tmp/owner-role.dump role_stub_source
if ! docker cp "${source_container}:/tmp/owner-role.dump" - 2>/dev/null \
  | docker cp - "${restore_container}:/tmp/" >/dev/null 2>&1; then
  echo "FAIL: owner-dump-transfer" >&2
  exit 1
fi
if ! docker exec "${restore_container}" pg_restore --list /tmp/owner-role.dump 2>/dev/null \
  | grep -vE '^[0-9]+; [0-9]+ [0-9]+ SCHEMA - public ' \
  | docker exec -i "${restore_container}" sh -c 'cat > /tmp/owner-toc.filtered' >/dev/null 2>&1; then
  echo "FAIL: owner-toc-filter" >&2
  exit 1
fi
if ! docker exec "${restore_container}" pg_restore --list /tmp/owner-role.dump 2>/dev/null \
  | grep -qE 'DEFAULT ACL public DEFAULT PRIVILEGES FOR TABLES synthetic_owner'; then
  echo "FAIL: synthetic-default-acl-not-in-dump" >&2
  exit 1
fi
quiet create-custom-restore-db docker exec -u postgres "${restore_container}" \
  createdb drill_custom
owner_restore_args=(pg_restore --no-owner --exit-on-error --single-transaction \
  --use-list=/tmp/owner-toc.filtered --dbname=drill_custom /tmp/owner-role.dump)
owner_restore_error=""
if owner_restore_error="$(docker exec -u postgres "${restore_container}" "${owner_restore_args[@]}" 2>&1)"; then
  echo "FAIL: restore-without-custom-acl-owner-unexpectedly-passed" >&2
  exit 1
fi
if [[ "${owner_restore_error}" != *'role "synthetic_owner" does not exist'* ]]; then
  echo "FAIL: custom-acl-owner-failed-for-unexpected-reason" >&2
  exit 1
fi
unset owner_restore_error
expect_value custom-owner-failure-rollback t docker exec -u postgres "${restore_container}" \
  psql -X -At -v ON_ERROR_STOP=1 -d drill_custom \
  -c "SELECT to_regclass('public.synthetic_owned') IS NULL"

echo "PASS: workflow restore SQL, fixed ACL stub, and custom-owner fail-closed behavior"

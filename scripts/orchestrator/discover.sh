#!/usr/bin/env bash
# Discover repository signals for orchestrator prioritization
# Output: orchestrator/discover.env (shell-sourceable)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=common.sh
source "$SCRIPT_DIR/common.sh"
orchestrator_require_jq
orchestrator_root

OUT="orchestrator/discover.env"
mkdir -p orchestrator

DATE="$(orchestrator_now)"
SHA="$(orchestrator_short_sha)"

# Governance gate (capture exit without failing)
GOV_EXIT=0
GOV_OUT="$(npm run cto:governance 2>&1)" || GOV_EXIT=$?
GOV_EXIT="${GOV_EXIT:-0}"

GATE_STATUS="$(echo "$GOV_OUT" | sed -n 's/.*Gate: \(PASS\|BLOCK\).*/\1/p' | tail -1)"
GATE_STATUS="${GATE_STATUS:-UNKNOWN}"

OVERALL="$(echo "$GOV_OUT" | grep 'Overall (weighted)' | grep -oE '[0-9]+' | head -1)"
GH_SCORE="$(echo "$GOV_OUT" | grep 'GitHub governance' | awk -F'|' '{gsub(/ /,"",$3); print $3}' | head -1)"
PROD_SCORE="$(echo "$GOV_OUT" | grep 'Production stability' | awk -F'|' '{gsub(/ /,"",$3); print $3}' | head -1)"
DRIFT_FAILURES="$(echo "$GOV_OUT" | sed -n 's/DOC_DRIFT_FAILURES=\([0-9]*\)/\1/p' | tail -1)"
DRIFT_WARNINGS="$(echo "$GOV_OUT" | sed -n 's/DOC_DRIFT_WARNINGS=\([0-9]*\)/\1/p' | tail -1)"

OVERALL="${OVERALL:-0}"
GH_SCORE="${GH_SCORE:-0}"
PROD_SCORE="${PROD_SCORE:-0}"
DRIFT_FAILURES="${DRIFT_FAILURES:-0}"
DRIFT_WARNINGS="${DRIFT_WARNINGS:-0}"

# GitHub exports (re-run hygiene lightweight if missing)
HYGIENE_OUT="$(bash scripts/cto-github-hygiene.sh 2>&1)" || true
eval "$(echo "$HYGIENE_OUT" | grep -E '^GITHUB_' || true)"

ISSUE_COUNT="${GITHUB_ISSUE_COUNT:-0}"
NON_DEP="${GITHUB_NON_DEP_PR_COUNT:-0}"
DRAFT_COUNT="${GITHUB_DRAFT_COUNT:-0}"
CURSOR_BRANCHES="${GITHUB_CURSOR_BRANCH_COUNT:-0}"
BOT_CAN_CLOSE="${GITHUB_BOT_CAN_CLOSE:-1}"

# Outcome measurement
OUTCOME_MEASURED=0
if [[ -f docs/OUTCOME_LOG.md ]]; then
  OD="$(sed -n '/^```outcome$/,/^```$/p' docs/OUTCOME_LOG.md | grep -E '^date:' | head -1 | sed 's/.*:[[:space:]]*//' | tr -d ' ')"
  [[ -n "$OD" && "$OD" != "null" ]] && OUTCOME_MEASURED=1
fi

# Orchestrator state
ITERATION_COUNT=0
LAST_TASK=""
if [[ -f orchestrator/state.json ]]; then
  ITERATION_COUNT="$(jq -r '.iteration_count // 0' orchestrator/state.json)"
  LAST_TASK="$(jq -r '.last_iteration.task_id // ""' orchestrator/state.json)"
fi

# Production SHA parity
PROD_SHA="$(curl -sf --max-time 10 "${PROD_URL:-https://sunrise-cafe-six.vercel.app}/api/version" 2>/dev/null | sed -n 's/.*"commit"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | cut -c1-7 || echo unknown)"
SHA_MATCH=0
[[ "$PROD_SHA" != "unknown" && "$SHA" != "unknown" && "$PROD_SHA" == "$SHA" ]] && SHA_MATCH=1

cat > "$OUT" <<EOF
# Auto-generated by scripts/orchestrator/discover.sh — do not edit
DISCOVER_AT="$DATE"
DISCOVER_SHA="$SHA"
GATE_STATUS="$GATE_STATUS"
GATE_EXIT="$GOV_EXIT"
OVERALL_HEALTH="$OVERALL"
GITHUB_SCORE="$GH_SCORE"
PRODUCTION_SCORE="$PROD_SCORE"
DOC_DRIFT_FAILURES="$DRIFT_FAILURES"
DOC_DRIFT_WARNINGS="$DRIFT_WARNINGS"
GITHUB_ISSUES="$ISSUE_COUNT"
GITHUB_NON_DEP_PRS="$NON_DEP"
GITHUB_DRAFT_PRS="$DRAFT_COUNT"
GITHUB_CURSOR_BRANCHES="$CURSOR_BRANCHES"
BOT_CAN_CLOSE="$BOT_CAN_CLOSE"
OUTCOME_MEASURED="$OUTCOME_MEASURED"
ITERATION_COUNT="$ITERATION_COUNT"
LAST_TASK_ID="$LAST_TASK"
PROD_SHA="$PROD_SHA"
SHA_MATCH="$SHA_MATCH"
EOF

echo "## Orchestrator Discover"
echo "_$DATE · \`$SHA\`_"
echo
echo "| Signal | Value |"
echo "|--------|------:|"
echo "| Gate | $GATE_STATUS (exit $GOV_EXIT) |"
echo "| Overall health | $OVERALL |"
echo "| GitHub score | $GH_SCORE |"
echo "| Doc drift failures | $DRIFT_FAILURES |"
echo "| Open issues | $ISSUE_COUNT |"
echo "| Non-dep PRs | $NON_DEP |"
echo "| Bot can close | $BOT_CAN_CLOSE |"
echo "| Outcome measured | $OUTCOME_MEASURED |"
echo "| Iterations completed | $ITERATION_COUNT |"
echo
echo "Wrote \`$OUT\`"

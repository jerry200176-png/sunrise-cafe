#!/usr/bin/env npx tsx
/**
 * Generate Weekly Executive Review markdown.
 * Usage: npm run executive:review [-- --week=2026-07-11]
 * Requires: NEXT_PUBLIC_SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY for live Observed values.
 */
import { writeFileSync, readFileSync, existsSync } from "fs";
import { join } from "path";
import { collectOutcomeMetrics } from "../src/lib/outcome-metrics";
import { buildNorthStarSnapshot } from "../src/lib/north-star-metrics";
import { buildExecutiveReview } from "../src/lib/executive-review";

const OUT_PATH = join(process.cwd(), "docs/internal/executive/WEEKLY_EXECUTIVE_REVIEW.md");
const weekArg = process.argv.find((a) => a.startsWith("--week="))?.split("=")[1];

async function main() {
  let northStar;
  try {
    const outcome = await collectOutcomeMetrics();
    northStar = buildNorthStarSnapshot(outcome);
  } catch (err) {
    console.warn("[executive:review] Live metrics unavailable:", (err as Error).message);
    console.warn("Writing template review without Observed values.");
    northStar = buildNorthStarSnapshot({
      collected_at: new Date().toISOString(),
      status: "unavailable",
      health_block: {
        date: new Date().toISOString().slice(0, 10),
        deposit_rate_pct: null,
        waitlist_conversion_pct: null,
        payment_review_oldest_hours: null,
        payment_review_sla_breached: false,
        migrations_all_applied: "no",
        overlap_constraint_active: "no",
        evidence_source: "offline-template",
        reviewer: "automated",
      },
      booking: { bookings_30d: 0, bookings_7d: 0, cancellation_rate_30d: null, cancellation_count_30d: 0 },
      payment: {
        deposit_rate_pct: null,
        deposit_paid_30d: 0,
        deposit_eligible_30d: 0,
        pending_reviews: 0,
        payment_review_oldest_hours: null,
        payment_review_median_hours_7d: null,
        payment_review_sla_compliance_pct_7d: null,
        payment_events_ready: false,
        deposit_at_risk: 0,
      },
      cancellation: { cancelled_30d: 0, auto_release_proxy_7d: 0 },
      refund: { tracked: false, note: "", rejected_payments_7d: 0 },
      waitlist: { joined_30d: 0, converted_30d: 0, conversion_pct: null },
      cron: {
        scheduled_jobs: [],
        deposit_reminders_7d: 0,
        tomorrow_reminders_pending: 0,
        auto_releases_7d: 0,
        job_runs_ready: false,
        jobs: [],
      },
      deployment: {
        commit: null,
        live_commit: null,
        live_commit_short: null,
        repository_commit: null,
        sha_parity: null,
        production_reachable: false,
        health_ok: false,
        service_role_configured: false,
      },
      migrations: {
        schema_migrations_table: false,
        applied: [],
        pending: [],
        all_required_applied: false,
        overlap_constraint_active: false,
        closed_dates_column: false,
        rbac_tables: false,
      },
      support: { pending_payment_reviews: 0, rejected_events_7d: 0, note: "" },
      funnel: {
        ops_events_ready: false,
        booking_flow_entered_7d: 0,
        booking_created_7d: 0,
        booking_conversion_pct: null,
        deposit_instructions_viewed_7d: 0,
        payment_clicks_7d: 0,
        payment_completion_pct: null,
        payment_approved_7d: 0,
        payment_approved_keyboard_7d: 0,
        keyboard_adoption_pct: null,
        freshest_ts: null,
      },
    });
  }

  const review = buildExecutiveReview(northStar, weekArg);
  const header = existsSync(OUT_PATH)
    ? readFileSync(OUT_PATH, "utf8").split("\n---\n\n# Weekly")[0] + "\n---\n\n"
    : "# Weekly Executive Review Archive\n\n> Auto-generated by `npm run executive:review`. Newest first.\n\n---\n\n";

  writeFileSync(OUT_PATH, header + review.markdown + "\n\n---\n\n", "utf8");
  console.log(`Wrote ${OUT_PATH} (week ${review.week_ending})`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
